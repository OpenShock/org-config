"""Turns a Result into commits, pull requests and API calls."""

import base64
from urllib.parse import quote

from . import gh
from .checks import Check
from .model import Repo, Result, read_at

FOOTER = 'Generated by [org-sync](https://github.com/{org}/org-config) from the org-wide desired state.'

# One branch and one pull request per repo, holding every check's file changes.
BRANCH = 'chore/org-sync'
TITLE = 'chore: sync with org-wide desired state'

COMMIT = '''
mutation($input: CreateCommitOnBranchInput!) {
  createCommitOnBranch(input: $input) { commit { oid url } }
}
'''


def _ref(slug: str, branch: str) -> str | None:
    try:
        return gh.api(f'repos/{slug}/git/ref/heads/{quote(branch)}')['object']['sha']
    except gh.GhError as e:
        if e.status == 404:
            return None
        raise


def _commit(repo: Repo, branch: str, head: str, files: dict[str, str | None], title: str, body: str) -> str:
    additions = [
        {'path': path, 'contents': base64.b64encode(content.encode('utf-8')).decode('ascii')}
        for path, content in files.items() if content is not None
    ]
    deletions = [{'path': path} for path, content in files.items() if content is None]
    # Commits made through this mutation are signed by GitHub and attributed to the token's user.
    data = gh.graphql(COMMIT, {'input': {
        'branch': {'repositoryNameWithOwner': repo.slug, 'branchName': branch},
        'expectedHeadOid': head,
        'message': {'headline': title, 'body': body},
        'fileChanges': {'additions': additions, 'deletions': deletions},
    }})
    commit = data['createCommitOnBranch']['commit']
    if branch == repo.default_branch:
        # Anything committed after this must build on it.
        repo.head_oid = commit['oid']
    return commit['url']


def merge(results: list[tuple[Check, Result]]) -> tuple[dict[str, str | None], str]:
    """Combines every check's file changes for one repo, plus a description grouped by check."""
    files: dict[str, str | None] = {}
    sections = []
    for check, result in results:
        proposed = {p: c for p, c in result.files.items() if p not in result.direct}
        if not proposed:
            continue
        files.update(proposed)
        sections.append('\n'.join([f'### {check.name}', *(f'- {d}' for d in result.details)]))
    return files, '\n\n'.join(sections)


def merge_direct(results: list[tuple[Check, Result]]) -> tuple[dict[str, str | None], str]:
    """The file changes that skip the pull request, plus a commit message body."""
    files: dict[str, str | None] = {}
    lines = []
    for _, result in results:
        files.update({p: c for p, c in result.files.items() if p in result.direct})
        lines += [f'- {d}' for d in result.direct_details]
    return files, '\n'.join(lines)


def deliver_files(repo: Repo, files: dict[str, str | None], body: str, direct: bool) -> str:
    """Commits all file changes for a repo as one commit and returns a line describing what happened."""
    if direct:
        url = _commit(repo, repo.default_branch, repo.head_oid, files, TITLE, body)
        return f'committed to {repo.default_branch}: {url}'

    open_prs = gh.api(f'repos/{repo.slug}/pulls?state=open&head={repo.org}:{quote(BRANCH)}')
    head = _ref(repo.slug, BRANCH)
    if head is not None and not open_prs:
        # Left over from an earlier PR that was merged or closed, start again from the default branch.
        gh.api(f'repos/{repo.slug}/git/refs/heads/{quote(BRANCH)}', 'DELETE')
        head = None

    if head is None:
        gh.api(f'repos/{repo.slug}/git/refs', 'POST', {'ref': f'refs/heads/{BRANCH}', 'sha': repo.head_oid})
        head = repo.head_oid
    else:
        # An open PR already exists, add a commit on top with whatever it does not contain yet.
        files = {p: c for p, c in files.items() if read_at(repo.slug, p, head) != c}
        if not files:
            return f'already proposed in {open_prs[0]["html_url"]}'

    _commit(repo, BRANCH, head, files, TITLE, body)
    description = f'{body}\n\n{FOOTER.format(org=repo.org)}'
    if open_prs:
        # Keep the description in step with what the PR now contains.
        gh.api(f'repos/{repo.slug}/pulls/{open_prs[0]["number"]}', 'PATCH', {'body': description})
        return f'updated {open_prs[0]["html_url"]}'
    pr = gh.api(f'repos/{repo.slug}/pulls', 'POST', {
        'title': TITLE,
        'head': BRANCH,
        'base': repo.default_branch,
        'body': description,
    })
    return f'opened {pr["html_url"]}'


def apply(repo: Repo, results: list[tuple[Check, Result]], direct: bool, only_direct: bool = False) -> list[str]:
    """Applies everything planned for one repo, returning a line per action taken or failed."""
    log = []
    files, body = merge_direct(results)
    if files:
        try:
            log.append(deliver_files(repo, files, body, direct=True))
        except gh.GhError as e:
            log.append(f'FAILED to commit files: {e.message}')
    if only_direct:
        return log
    files, body = merge(results)
    if files:
        try:
            log.append(deliver_files(repo, files, body, direct))
        except gh.GhError as e:
            log.append(f'FAILED to commit files: {e.message}')
    for check, result in results:
        for change in result.api:
            try:
                gh.api(change.endpoint, change.method, change.body)
                log.append(f'[{check.name}] done: {change.summary}')
            except gh.GhError as e:
                log.append(f'FAILED [{check.name}] {change.summary}: {e.message}')
    return log
